def generate_rounded_rotated_rectangle(
    size,
    center_x,
    center_y,
    half_long_side,
    half_short_side,
    angle_degrees,
    corner_radius
):
    """
    Generates a 2D NumPy array representing a rectangle with rounded corners,
    rotated by the given angle.

    Args:
        size (int): The dimension of the square output array (size x size).
        center_x (float): The x-coordinate of the rectangle's center.
        center_y (float): The y-coordinate of the rectangle's center.
        half_long_side (float): Half the length of the longer side of the rectangle.
        half_short_side (float): Half the length of the shorter side of the rectangle.
        angle_degrees (float): The rotation angle of the rectangle in degrees.
        corner_radius (float): The radius of the rounded corners.

    Returns:
        np.ndarray: A 2D NumPy array of size x size, with 1 inside the rounded
                    rotated rectangle and -1 outside.
    """
    # Ensure corner_radius does not exceed half of the shorter side for valid geometry
    corner_radius = min(corner_radius, half_long_side, half_short_side)

    x_coords = np.linspace(-100, 100, size)
    y_coords = np.linspace(-100, 100, size)
    X, Y = np.meshgrid(x_coords, y_coords)

    translated_X = X - center_x
    translated_Y = Y - center_y

    angle_radians = np.deg2rad(angle_degrees)

    rotated_X = translated_X * np.cos(angle_radians) + translated_Y * np.sin(angle_radians)
    rotated_Y = -translated_X * np.sin(angle_radians) + translated_Y * np.cos(angle_radians)

    # Condition for the main body of the rectangle (excluding corners)
    inside_main_body = (
        (np.abs(rotated_X) <= (half_long_side - corner_radius)) & (np.abs(rotated_Y) <= half_short_side) |
        (np.abs(rotated_Y) <= (half_short_side - corner_radius)) & (np.abs(rotated_X) <= half_long_side)
    )

    # Conditions for the rounded corners
    # Calculate distances from the center of the quarter circles
    rx_corner_dist = np.abs(rotated_X) - (half_long_side - corner_radius)
    ry_corner_dist = np.abs(rotated_Y) - (half_short_side - corner_radius)

    inside_rounded_corners = (
        (rx_corner_dist > 0) & (ry_corner_dist > 0) &
        (rx_corner_dist**2 + ry_corner_dist**2 <= corner_radius**2)
    )

    # Combine conditions
    inside_rectangle = inside_main_body | inside_rounded_corners

    rectangle_array = np.full((size, size), -1.0)
    rectangle_array[inside_rectangle] = 1.0

    return rectangle_array

