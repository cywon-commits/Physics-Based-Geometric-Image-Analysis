def zoom_image(image_array, zoom_factor):
  # Get current shape
  original_height, original_width = image_array.shape

  # Calculate the zoom factor for each dimension
  zoom_factor_h = zoom_factor
  zoom_factor_w = zoom_factor

  # Enlarge the image_array
  enlarged_image_array = zoom(image_array, (zoom_factor_h, zoom_factor_w), order=0) # order=0 for nearest-neighbor interpolation, suitable for binary-like data

  # Update image_array to the enlarged version for subsequent operations
  return enlarged_image_array

def extract_binary_images(img_array, step = 32):
  binary_images = []
  for channel in range(img_array.shape[2]):
    binary_image = img_array[:,:,channel]
    for threshold in range(step, 256, step):
      target_image = np.where(binary_image < threshold, -1, 1)
      binary_images.append(target_image)
  return binary_images

import numpy as np

def _dot_product(v1, v2):
    """Calculates the dot product of two 3D vectors."""
    return np.dot(v1, v2)

def _cross_product(v1, v2):
    """Calculates the cross product of two 3D vectors."""
    return np.cross(v1, v2)

def _mixed_product(a, b, c):
    """Calculates the scalar triple product: a dot (b cross c)."""
    return _dot_product(a, _cross_product(b, c))

def solid_angle_from_three_vectors(a, b, c):
    """
    Calculates the solid angle formed by three vectors a, b, c according to the user's formula.
    Assumes a, b, c are 3D numpy arrays (unit vectors from S array).
    The formula is: 2 * arctan ( |abc| / (abc + (a dot b)c + (a dot c)b + (b dot c)a ) )
    where |abc| = a dot (b cross c).

    Interpretation for the denominator to be a scalar, given a, b, c are unit vectors:
    - 'abc' in the denominator is interpreted as `np.abs(a dot (b cross c))`.
    - For terms like '(a dot b)c', 'c' is interpreted as its magnitude (which is 1 for unit vectors).
      So (a dot b)c becomes (a dot b) * 1, and similarly for other terms.
    This leads to a denominator: `np.abs(scalar_triple_prod) + (a dot b) + (a dot c) + (b dot c)`.
    """
    scalar_triple_prod = _mixed_product(a, b, c)
    # mixed_prod_abs = np.abs(scalar_triple_prod)

    # Denominator interpretation based on unit vectors and scalar requirement
    denom = (1 + #mixed_prod_abs +
             _dot_product(a, b) +
             _dot_product(a, c) +
             _dot_product(b, c))

    # Handle potential division by zero. If mixed_prod_abs is 0, vectors are coplanar, solid angle is 0.
    if denom == 0:
        return 0.0

    return 2 * np.arctan(scalar_triple_prod / denom)

def calculate_omega(S):
    """
    Calculates the Omega(i,j) array based on the S field.
    Omega(i,j) is the sum of two solid angles:
    1. Solid angle of S[i,j], S[i+1,j], S[i,j+1]
    2. Solid angle of S[i+1,j], S[i,j+1], S[i+1,j+1]
    """
    height, width, _ = S.shape
    # Omega array will have dimensions (height-1, width-1) because we look at neighboring cells
    Omega = np.zeros((height - 1, width - 1))

    for i in range(height - 1):
        for j in range(width - 1):
            # First set of vectors for solid angle 1
            a1 = S[i, j]
            c1 = S[i + 1, j]
            b1 = S[i, j + 1]
            sa1 = solid_angle_from_three_vectors(a1, b1, c1)

            # Second set of vectors for solid angle 2
            a2 = S[i + 1, j]
            b2 = S[i, j + 1]
            c2 = S[i + 1, j + 1]
            sa2 = solid_angle_from_three_vectors(a2, b2, c2)

            Omega[i, j] = sa1 + sa2
    return Omega

import numpy as np

def signed_planar_angle(v1, v2):
    """
    Calculates the signed planar angle from vector v1 to vector v2 in 2D.
    The angle is in radians in the range (-pi, pi].
    v1 and v2 are 2D numpy arrays.
    """
    # Cross product for 2D vectors (z-component of 3D cross product)
    cross_prod_z = v1[0] * v2[1] - v1[1] * v2[0]
    dot_prod = np.dot(v1, v2)

    # Handle zero vectors to avoid NaN or division by zero in arctan2 if both are zero
    # np.arctan2 handles cases where one argument is zero, but if both are zero it returns 0.0
    # which is appropriate here for non-contributing zero vectors.
    return np.arctan2(cross_prod_z, dot_prod)

def calculate_q(Tex, factor=0.5):
    """
    Calculates the topological charge Q(i,j) for each cell in the Tex field.
    Tex is a (H, W, 2) numpy array representing 2D vectors.
    Q(i,j) is the sum of signed planar angles around a cell divided by 2*pi,
    then rounded to the nearest integer.
    If the magnitude of any corner vector is below factor * (average Tex magnitude), Q(i,j) is np.nan.
    """
    height, width, _ = Tex.shape
    # Q array will have dimensions (height-1, width-1) because we look at neighboring cells
    Q = np.zeros((height - 1, width - 1))

    # Calculate average magnitude of all Tex vectors once
    all_tex_magnitudes = np.sqrt(Tex[:,:,0]**2 + Tex[:,:,1]**2)
    average_tex_magnitude = np.average(all_tex_magnitudes)
    threshold = factor * average_tex_magnitude

    for i in range(height - 1):
        for j in range(width - 1):
            v_ij = Tex[i, j]
            v_i_plus_1_j = Tex[i + 1, j]
            v_i_plus_1_j_plus_1 = Tex[i + 1, j + 1]
            v_i_j_plus_1 = Tex[i, j + 1]

            # Calculate magnitudes of corner vectors
            mag_ij = np.sqrt(v_ij[0]**2 + v_ij[1]**2)
            mag_i_plus_1_j = np.sqrt(v_i_plus_1_j[0]**2 + v_i_plus_1_j[1]**2)
            mag_i_plus_1_j_plus_1 = np.sqrt(v_i_plus_1_j_plus_1[0]**2 + v_i_plus_1_j_plus_1[1]**2)
            mag_i_j_plus_1 = np.sqrt(v_i_j_plus_1[0]**2 + v_i_j_plus_1[1]**2)

            # Check if any corner vector's magnitude is below the threshold
            if (mag_ij < threshold or
                mag_i_plus_1_j < threshold or
                mag_i_plus_1_j_plus_1 < threshold or
                mag_i_j_plus_1 < threshold):
                Q[i, j] = np.nan # Use np.nan for missing/invalid data in numerical arrays
                continue # Skip angle calculation for this cell

            # Calculate the four signed planar angles
            angle1 = signed_planar_angle(v_ij, v_i_plus_1_j)
            angle2 = signed_planar_angle(v_i_plus_1_j, v_i_plus_1_j_plus_1)
            angle3 = signed_planar_angle(v_i_plus_1_j_plus_1, v_i_j_plus_1)
            angle4 = signed_planar_angle(v_i_j_plus_1, v_ij)

            # Sum the angles
            total_angle_sum = angle1 + angle2 + angle3 + angle4

            # Calculate topological charge and round to nearest integer
            # This effectively counts how many times the vectors wind around the cell.
            Q[i, j] = np.round(total_angle_sum / (2 * np.pi))
    return Q

