default_conversion = 2/37

def run_spin_simulation(
    initial_array_2d,
    kernel_dmx = default_kernel_dmx,
    parameters = default_parameters,
    conVersionFactor = default_conversion,
    blocksize = 1
):

    kernel_dmy = np.transpose(kernel_dmx)
    kernel_dmz = np.zeros((5, 5))
    kernel_HJ = kernel_dmx * kernel_dmx + kernel_dmy * kernel_dmy

    d_coeff, c_coeff, num_iterations = parameters

    # Initialize S fields
    Sx = np.zeros_like(initial_array_2d)
    Sy = np.zeros_like(initial_array_2d)
    Sz = initial_array_2d.copy() # Use a copy to avoid modifying the original input

    # Initialize fixed HOx, HOy, HOz values based on the initial S fields

    HOx_fixed = Sx.copy()
    HOy_fixed = Sy.copy()
    HOz_fixed = Sz.copy()

    if blocksize > 1:
      mask = centerMask(initial_array_2d.shape, blocksize)
      HOx_fixed = np.where(mask, HOx_fixed, 0)
      HOy_fixed = np.where(mask, HOy_fixed, 0)
      HOz_fixed = np.where(mask, HOz_fixed, 0)



    # Initialize lists to store energy values
    et_values = []
    ej_values = []

    # Main simulation loop
    for i in range(num_iterations):
        # a. Calculate HJx, HJy, and HJz by convolving Sx, Sy, and Sz with kernel_HJ
        HJx = convolve2d(Sx, kernel_HJ, mode='same', boundary='symm')
        HJy = convolve2d(Sy, kernel_HJ, mode='same', boundary='symm')
        HJz = convolve2d(Sz, kernel_HJ, mode='same', boundary='symm')

        # b. Calculate HDx, HDy, and HDz by convolving Sz with derivative kernels
        HDx = convolve2d(Sz, kernel_dmx, mode='same', boundary='symm')
        HDy = convolve2d(Sz, kernel_dmy, mode='same', boundary='symm')
        HDz = convolve2d(Sz, kernel_dmz, mode='same', boundary='symm')

        # d, e, f. Calculate HTx, HTy, and HTz
        HTx = HJx + d_coeff * HDx + c_coeff * HOx_fixed
        HTy = HJy + d_coeff * HDy + c_coeff * HOy_fixed
        HTz = HJz + d_coeff * HDz + c_coeff * HOz_fixed

        # g. Calculate the magnitude of the HT vector at each point
        magnitudes_HT = np.sqrt(HTx**2 + HTy**2 + HTz**2)

        # h. Create a boolean mask to identify points where magnitudes are zero
        zero_magnitudes_HT_mask = (magnitudes_HT == 0)

        # i. Create a reciprocal of magnitudes, handling division by zero
        inv_magnitudes_HT = np.where(zero_magnitudes_HT_mask, 0, 1 / magnitudes_HT)

        # j. Normalize HT components to get the new S components
        Sx_new = HTx * inv_magnitudes_HT
        Sy_new = HTy * inv_magnitudes_HT
        Sz_new = HTz * inv_magnitudes_HT

        # Calculate UJ = -HJ . S
        UJ = -(HJx * Sx_new + HJy * Sy_new + HJz * Sz_new)


        # Calculate UD = -d_coeff * (HD . S)
        UD = -d_coeff * (HDx * Sx_new + HDy * Sy_new + HDz * Sz_new)

        # Calculate UO = -c_coeff * (HO . S), using the fixed HO values
        UO = -c_coeff * (HOx_fixed * Sx_new + HOy_fixed * Sy_new + HOz_fixed * Sz_new)

        UT = UJ + UD + UO

        # Calculate and store average energy values
        ET = UT
        et_values.append(np.average(ET))
        EJ = UJ + np.sum(kernel_HJ)
        ej_values.append(np.sum(EJ))

        # k. Update Sx, Sy, and Sz for the next iteration
        Sx = Sx_new
        Sy = Sy_new
        Sz = Sz_new

    Tx = (HJx * Sx_new - HJy * Sy_new)*conVersionFactor
    Ty = (HJx * Sy_new + HJy * Sx_new)*conVersionFactor

    magnitude = np.sqrt(Tx**2 + Ty**2)
    angle = -np.pi/2+np.arctan2(Ty, Tx)/2 # in radians

    OrX = magnitude * np.cos(angle)
    OrY = magnitude * np.sin(angle)

    txSum = np.sum(Tx)
    tySum = np.sum(Ty)

    tiltingAmount = np.sqrt(txSum**2 + tySum**2)
    tiltingAngle = 45-90/np.pi*np.atan2(-np.array(txSum), -np.array(tySum))
    totalAmount = np.sum(magnitude)

    return totalAmount, tiltingAmount, tiltingAngle, np.stack([Sx, Sy, Sz], axis = -1), ET, EJ, np.stack([Tx, Ty], axis = -1), np.stack([OrX, OrY], axis = -1), magnitude, angle, et_values, ej_values

