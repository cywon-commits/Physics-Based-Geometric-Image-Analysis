def angleHistogram(OrTheta, OrMag, factor = 1):
  OrMagAverage = np.average(OrMag)
  # Flatten OrMag and OrTheta arrays for easier filtering
  or_mag_flat = OrMag.flatten()
  or_theta_flat = OrTheta.flatten()

  # Create a boolean mask for OrMag values greater than OrMagAverage
  mask = or_mag_flat > OrMagAverage * factor

  # Apply the mask to OrTheta to get the filtered values
  filtered_or_theta = or_theta_flat[mask]

  # Convert filtered_or_theta from radians to degrees and take the absolute value
  filtered_or_theta_degrees_abs = np.abs(filtered_or_theta * (180 / np.pi))

  # Convert back to radians for polar plotting, ensure in [0, pi) range
  angles_radians = (filtered_or_theta_degrees_abs % 180) * (np.pi / 180)

  # Create histogram bins
  bins = np.linspace(0, np.pi, 90) # 90 bins for 0 to 180 degrees (pi radians)
  counts, bin_edges = np.histogram(angles_radians, bins=bins, density=True)

  # Prepare for polar plot
  widths = np.diff(bin_edges)
  centers = (bin_edges[:-1] + bin_edges[1:]) / 2

  fig, ax = plt.subplots(figsize=(10, 8), subplot_kw={'projection': 'polar'})

  # Plot the histogram for 0-180 degrees
  ax.bar(centers, counts, width=widths, color='blue', alpha=0.75, bottom=0)

  # Plot the mirrored histogram for 180-360 degrees by shifting centers by pi
  ax.bar(centers + np.pi, counts, width=widths, color='blue', alpha=0.75, bottom=0)

  ax.set_theta_zero_location('N') # Set 0 degrees to the top
  ax.set_theta_direction(-1) # Clockwise direction for angles

  # Set degree labels for a full 360-degree circle
  ax.set_xticks(np.deg2rad([0, 45, 90, 135, 180, 225, 270, 315]))
  ax.set_xticklabels(['0°', '45°', '90°', '135°', '180°', '225°', '270°', '315°'])

  ax.set_title('Radial Histogram of OrTheta (180-degree periodicity) where OrMag > {} * OrMagAverage'.format(factor))
  plt.show()
  return filtered_or_theta_degrees_abs

