def block_average(Tex, block_size):
  current_h, current_w, current_c = Tex.shape

  # Calculate padding needed to make dimensions divisible by block_size
  pad_h = (block_size - (current_h % block_size)) % block_size
  pad_w = (block_size - (current_w % block_size)) % block_size

  # Pad the Tex array with zeros
  padded_Tex = np.pad(Tex, ((0, pad_h), (0, pad_w), (0, 0)), mode='constant')

  # Get new dimensions after padding
  new_h, new_w, _ = padded_Tex.shape

  # Reshape and average over 5x5 blocks
  averaged_Tex = padded_Tex.reshape(
      new_h // block_size, block_size,
      new_w // block_size, block_size,
      current_c
  ).mean(axis=(1, 3))

  return averaged_Tex

def TexToOr(Tex, block_size = 1, magMinMax = (0,10)):
  if block_size > 1:
    Tex = block_average(Tex, block_size)
  Tx = Tex[:,:,0]
  Ty = Tex[:,:,1]
  magnitude = np.ones_like(Tx)
  variable_magnitude = np.sqrt(Tx**2 + Ty**2)
  magnitude = np.where(variable_magnitude < magMinMax[0], 0, np.where(variable_magnitude > magMinMax[1], 1, variable_magnitude))
  angle = -np.pi/2+np.arctan2(Ty, Tx)/2 # in radians

  OrX = magnitude * np.cos(angle)
  OrY = magnitude * np.sin(angle)
  return np.stack([OrX, OrY], axis = -1)

