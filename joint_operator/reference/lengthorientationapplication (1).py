import numpy as np

def centerMask(size, blocksize):
  height, width = size
  mask = np.full(size, False, dtype=bool)

  center_offset = blocksize // 2

  for i in range(height):
    for j in range(width):
      if (i % blocksize == center_offset) and (j % blocksize == center_offset):
        mask[i, j] = True
  return mask

