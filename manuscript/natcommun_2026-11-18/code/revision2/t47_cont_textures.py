def raw_cont(img,smooth=.8,h=2.0):
    """pixel-level outer products of v generated by the continuous source; g = intensity normalized between its 2% and 98% quantiles"""
    sm=ndi.gaussian_filter(img,smooth); lo,hi=np.quantile(sm,(.02,.98)); g=np.clip((sm-lo)/(hi-lo),0,1)
    vr,vc,s=gen_gray(2*g-1,h=h,full=True); return np.stack([vr*vr,vc*vc,vr*vc])
RAW={'PBGIA_cuts':raw_tensor,'PBGIA_cont':raw_cont,'ST':st_raw}
def rot_q(q,theta):
    re=ndi.rotate(q.real,-theta,reshape=False,order=1,mode='reflect'); im=ndi.rotate(q.imag,-theta,reshape=False,order=1,mode='reflect')
    return (re+1j*im)*np.exp(-2j*np.deg2rad(theta))
def real_job(idx):
    nm,img,_,truth=mt.construct_cases()[idx]; rimg=img_rotate(img,10); roi=roi_center(img.shape,.6); rows=[]
    for m,f in RAW.items():
        R0=f(img); R1=f(rimg)
        for s in [2,3,4,6,8,12,16]:
            q0,_=qfield(R0,s); q1b=rot_q(qfield(R1,s)[0],10); w=np.abs(q0)*np.abs(q1b)*roi
            d=np.abs((np.angle(q1b)-np.angle(q0)+np.pi)%(2*np.pi)-np.pi)/2
            gt=np.nan
            if truth is not None: tan=tangent_deg(q0); gt=float(np.mean(np.abs((tan[roi]-truth[roi]+90)%180-90)))
            rows.append(dict(image=nm,method=m,sigma=s,local_rot_err=float(np.degrees((w*d).sum()/w.sum())),gt_err=gt,n_defects=len(defect_list(q0,margin=24))))
    return rows
def lic_rows():
    n=320; y,x=np.mgrid[:n,:n]+0.0; truth=[(110,100,+.5),(110,140,-.5),(220,110,+.5),(220,220,-.5)]
    psi=np.zeros((n,n))
    for r0,c0,k in truth: psi+=k*np.arctan2(-(y-r0),x-c0)
    img=np.load('/home/claude/work/manuscript_v2/data/revision2/t15_lic_img.npy')
    def match(defs,rad):
        used=set(); hit=0
        for r0,c0,k0 in truth:
            for i,(r,c,k) in enumerate(defs):
                if i not in used and k==k0 and np.hypot(r-r0,c-c0)<=rad: used.add(i); hit+=1; break
        return hit
    excl=np.ones((n,n),bool)
    for r0,c0,_ in truth: excl&=np.hypot(y-r0,x-c0)>20
    inner=(y>24)&(y<n-24)&(x>24)&(x<n-24)&excl; rows=[]
    R={m:f(img) for m,f in RAW.items()}
    for s in [1.5,2,3,4,6,8,10,12,14,16,18,20,24,28,32,40,50]:
        for m,Rm in R.items():
            q,_=qfield(Rm,s); d=defect_list(q,margin=24); err=np.abs((tangent_deg(q)-np.degrees(psi)%180+90)%180-90)
            rows.append(dict(method=m,sigma=s,n_plus=sum(z[2]>0 for z in d),n_minus=sum(z[2]<0 for z in d),net=sum(z[2] for z in d),matched=match(d,max(6,s)),local_err=float(np.mean(err[inner]))))
    return rows
def save(rows,fn):
    with open(fn,'w',newline='') as f: w=csv.DictWriter(f,fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
